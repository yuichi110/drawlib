class CustomIcon:
    """Wrapper for custom icons (image paths, Dimage instances, or PIL images)."""

    def __init__(self, image: str | Path | Dimage | Image | CustomIcon) -> None:
        """Initialize CustomIcon.

        Args:
            image: Image file path, Dimage instance, PIL Image, or another CustomIcon.

        Raises:
            ValueError: If the provided image type is not supported.
        """
        if isinstance(image, CustomIcon):
            self._dimage = image.dimage.copy()
        elif isinstance(image, (str, Path)):
            self._dimage = Dimage(str(image))
        elif isinstance(image, Dimage):
            self._dimage = image.copy()
        elif isinstance(image, Image):
            self._dimage = Dimage(image)
        else:
            raise ValueError(f"CustomIcon does not support image of type '{type(image)}'.")

    @property
    def dimage(self) -> Dimage:
        """Get the underlying Dimage instance."""
        return self._dimage

    def copy(self) -> CustomIcon:
        """Create a deep copy of this CustomIcon."""
        return CustomIcon(self._dimage.copy())
