_META_REFRESH_RE = re.compile(r'<meta\s+http-equiv=["\']refresh["\']', re.IGNORECASE)
_HTML_LANG_RE = re.compile(r'<html\b[^>]*\blang=["\']([^"\']+)["\']', re.IGNORECASE)
_BODY_OPEN_RE = re.compile(r"(<body\b[^>]*>)\r?\n?", re.IGNORECASE)
_EXISTING_BANNER_RE = re.compile(
    r'[ \t]*<div class="demo-banner"[\s\S]*?</div>\s*</div>\r?\n?',
)


def detect_portal_id(rel_parts: tuple[str, ...]) -> str:
    """Identify which documentation portal an HTML file belongs to.

    Args:
        rel_parts: Path components relative to the docs/ root directory.

    Returns:
        Portal identifier string ('user_guide', 'api', 'architecture',
        'quickstart', 'about-drawlib', 'jupyter', or 'pni501').
    """
    if not rel_parts:
        return "user_guide"
    first = rel_parts[0]
    if first in ("api", "architecture", "quickstart", "about-drawlib", "jupyter"):
        return first
    if len(rel_parts) >= 2 and first == "reports" and rel_parts[1] == "pni-full-audit":
        return "pni501"
    return "user_guide"


def should_skip_html(html_path: Path, content: str) -> bool:
    """Return True if the HTML file should not receive a top banner.

    Args:
        html_path: Path to the HTML file.
        content: Raw HTML file content.

    Returns:
        True if the file is 404.html, a meta-refresh redirect, or lacks <body>.
    """
    if html_path.name == "404.html":
        return True
    if _META_REFRESH_RE.search(content):
        return True
    return not bool(_BODY_OPEN_RE.search(content))


def is_japanese_html(content: str) -> bool:
    """Detect whether the HTML document declares a Japanese locale.

    Args:
        content: Raw HTML file content.

    Returns:
        True if <html lang="..."> starts with 'ja'.
    """
    match = _HTML_LANG_RE.search(content)
    return bool(match and match.group(1).strip().lower().startswith("ja"))


def render_banner_html(
    portal_id: str,
    is_ja: bool,
    rel_parts: tuple[str, ...],
    docs_root: Path,
) -> str:
    """Render the .demo-banner HTML block for a specific HTML page.

    Args:
        portal_id: Portal identifier ('user_guide', 'api', etc.).
        is_ja: Whether the current page is Japanese.
        rel_parts: Tuple of path parts relative to docs_root.
        docs_root: Root directory of built documentation (docs/).

    Returns:
        Formatted HTML string for the .demo-banner block.
    """
    lang = "ja" if is_ja else "en"
    rel_to_docs = "../" * (len(rel_parts) - 1)
    banner_text = PORTAL_TEXT_MAP[portal_id][lang]

    portal_nav: list[tuple[str, str, str]] = [
        ("user_guide", "User Guide", f"{rel_to_docs}ja/index.html" if is_ja else f"{rel_to_docs}index.html"),
        ("api", "API Reference", f"{rel_to_docs}api/ja/index.html" if is_ja else f"{rel_to_docs}api/index.html"),
        ("architecture", "Architecture", f"{rel_to_docs}architecture/index.html"),
        (
            "quickstart",
            "Quickstart",
            f"{rel_to_docs}quickstart/ja/index.html" if is_ja else f"{rel_to_docs}quickstart/en/index.html",
        ),
        (
            "about-drawlib",
            "Slide Deck",
            f"{rel_to_docs}about-drawlib/ja/index.html" if is_ja else f"{rel_to_docs}about-drawlib/en/index.html",
        ),
        (
            "jupyter",
            "Jupyter / Colab",
            f"{rel_to_docs}jupyter/ja/index.html" if is_ja else f"{rel_to_docs}jupyter/en/index.html",
        ),
        ("pni501", "PNI501 Audit", f"{rel_to_docs}reports/pni-full-audit/index.html"),
    ]

    link_items: list[str] = []
    for pid, label, href in portal_nav:
        if pid == portal_id:
            link_items.append(f"<strong>{label}</strong>")
        else:
            link_items.append(f'<a href="{href}">{label}</a>')

    if portal_id == "quickstart":
        pdf_rel = f"quickstart/quickstart_{lang}.pdf"
        docx_rel = f"quickstart/quickstart_{lang}.docx"
        if (docs_root / pdf_rel).exists():
            link_items.append(f'<a href="{rel_to_docs}{pdf_rel}">PDF</a>')
        if (docs_root / docx_rel).exists():
            link_items.append(f'<a href="{rel_to_docs}{docx_rel}">DOCX</a>')
    elif portal_id == "about-drawlib":
        pdf_rel = f"about-drawlib/about-drawlib_{lang}.pdf"
        pptx_rel = f"about-drawlib/about-drawlib_{lang}.pptx"
        if (docs_root / pdf_rel).exists():
            link_items.append(f'<a href="{rel_to_docs}{pdf_rel}">PDF</a>')
        if (docs_root / pptx_rel).exists():
            link_items.append(f'<a href="{rel_to_docs}{pptx_rel}">PPTX</a>')
    elif portal_id == "pni501":
        pdf_rel = "reports/pni-full-audit/full_audit.pdf"
        if (docs_root / pdf_rel).exists():
            link_items.append(f'<a href="{rel_to_docs}{pdf_rel}">PDF</a>')

    link_items.append('<a href="https://examples.drawlib.com/" target="_blank" rel="noopener noreferrer">Examples ↗</a>')
    link_items.append(
        '<a href="https://github.com/yuichi110/drawlib" target="_blank" rel="noopener noreferrer">GitHub ↗</a>'
    )

    sep = '\n                <span class="demo-banner-sep">·</span>\n                '
    joined_links = sep.join(link_items)

    return (
        '    <div class="demo-banner" role="region" aria-label="Portal Navigation">\n'
        '        <div class="demo-banner-inner">\n'
        '            <span class="demo-banner-badge">DRAWLIB OFFICIAL</span>\n'
        '            <span class="demo-banner-text">\n'
        f"                {banner_text}\n"
        "            </span>\n"
        '            <span class="demo-banner-links">\n'
        f"                {joined_links}\n"
        "            </span>\n"
        "        </div>\n"
        "    </div>\n"
    )


def inject_banner_into_html(html_path: Path, docs_root: Path) -> bool:
    """Idempotently inject or update .demo-banner in an HTML file.

    Args:
        html_path: Path to the HTML file.
        docs_root: Root directory of built documentation (docs/).

    Returns:
        True if the file was modified (or already had a banner), False if skipped.
    """
    content = html_path.read_text(encoding="utf-8")
    if should_skip_html(html_path, content):
        return False

    rel_parts = html_path.relative_to(docs_root).parts
    portal_id = detect_portal_id(rel_parts)
    is_ja = is_japanese_html(content)
    banner_html = render_banner_html(portal_id, is_ja, rel_parts, docs_root)

    if _EXISTING_BANNER_RE.search(content):
        updated = _EXISTING_BANNER_RE.sub(banner_html, content, count=1)
    else:
        updated = _BODY_OPEN_RE.sub(rf"\g<1>\n{banner_html}", content, count=1)

    if updated != content:
        html_path.write_text(updated, encoding="utf-8")
    return True


def inject_banner_into_css(css_path: Path) -> bool:
    """Idempotently append or update .demo-banner styles in a style.css file.

    Args:
        css_path: Path to the style.css file.

    Returns:
        True if the file was processed.
    """
    content = css_path.read_text(encoding="utf-8")
    css_block = BANNER_CSS.strip() + "\n"
    if CSS_MARKER in content:
        prefix = content.split(CSS_MARKER, maxsplit=1)[0].rstrip()
        updated = f"{prefix}\n\n{css_block}"
    else:
        updated = f"{content.rstrip()}\n\n{css_block}"

    if updated != content:
        css_path.write_text(updated, encoding="utf-8")
    return True


def patch_slide_js(slide_js_path: Path) -> bool:
    """Idempotently patch slide.js so 16:9 stage scaling accounts for .demo-banner height.

    Args:
        slide_js_path: Path to docs/about-drawlib/slide.js.

    Returns:
        True if the file exists and was processed, False otherwise.
    """
    if not slide_js_path.exists():
        return False

    content = slide_js_path.read_text(encoding="utf-8")
    updated = content

    target_scale_snippet = "    const windowWidth = window.innerWidth;\n    const windowHeight = window.innerHeight;"
    replacement_scale_snippet = (
        "    const windowWidth = window.innerWidth;\n"
        "    const bannerEl = document.querySelector('.demo-banner');\n"
        "    const bannerH = (bannerEl && !document.fullscreenElement && !isPresenterMode)"
        " ? (bannerEl.offsetHeight || 38) : 0;\n"
        "    document.documentElement.style.setProperty('--demo-banner-h', `${bannerH}px`);\n"
        "    const windowHeight = Math.max(100, window.innerHeight - bannerH);"
    )

    if "const bannerEl = document.querySelector('.demo-banner');" not in updated:
        updated = updated.replace(target_scale_snippet, replacement_scale_snippet, 1)

    target_listener_snippet = "  window.addEventListener('resize', updateScale);"
    replacement_listener_snippet = (
        "  window.addEventListener('resize', updateScale);\n"
        "  window.addEventListener('load', updateScale);\n"
        "  document.addEventListener('fullscreenchange', updateScale);"
    )
    if "document.addEventListener('fullscreenchange', updateScale);" not in updated:
        updated = updated.replace(target_listener_snippet, replacement_listener_snippet, 1)

    if updated != content:
        slide_js_path.write_text(updated, encoding="utf-8")
    return True


def inject_portal_banners(docs_root: Path | None = None) -> tuple[int, int]:
    """Inject .demo-banner HTML, CSS, and slide.js patches across all portals in docs/.

    Args:
        docs_root: Root directory of built documentation. Defaults to PROJECT_ROOT / 'docs'.

    Returns:
        Tuple of (processed_html_count, processed_css_count).
    """
    root = docs_root if docs_root is not None else PROJECT_ROOT / "docs"
    if not root.exists():
        return 0, 0

    html_count = 0
    for html_path in sorted(root.rglob("*.html")):
        if inject_banner_into_html(html_path, root):
            html_count += 1

    css_count = 0
    for css_path in sorted(root.rglob("style.css")):
        if inject_banner_into_css(css_path):
            css_count += 1

    patch_slide_js(root / "about-drawlib" / "slide.js")
    console.print(
        f"[dim]Injected .demo-banner into {html_count} HTML file(s) and {css_count} style.css file(s) in {root.name}/.[/dim]"
    )
    return html_count, css_count
