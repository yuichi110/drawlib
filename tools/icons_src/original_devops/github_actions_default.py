def _sc(pt: tuple[float, float]) -> tuple[float, float]:
    return (50.0 + (pt[0] - 50.0) * scale, 50.0 + (pt[1] - 50.0) * scale)


def _sc_list(pts: list[tuple[float, float]]) -> list[tuple[float, float]]:
    return [_sc(p) for p in pts]


def _circle_pts(xc: float, yc: float, r: float, steps: int = 64) -> list[tuple[float, float]]:
    return [
        (xc + r * math.cos(2.0 * math.pi * i / steps), yc + r * math.sin(2.0 * math.pi * i / steps))
        for i in range(steps)
    ]


