def _pt(p: tuple[float, float]) -> tuple[float, float]:
    return (50.0 + (p[0] - 50.0) * s, 50.0 + (p[1] - 50.0) * s)


def _sc(pts: list[tuple[float, float]]) -> list[tuple[float, float]]:
    return [_pt(p) for p in pts]


